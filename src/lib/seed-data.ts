function getNextScheduleDates(): { dropDate: string; cutoffIso: string } {
  const now = new Date();
  // Find upcoming Sunday (or next Sunday if today is Sunday after 6 PM)
  const day = now.getDay();
  const daysToSunday = day === 0 ? 7 : 7 - day;
  const sunday = new Date(now);
  sunday.setDate(now.getDate() + daysToSunday);

  const friday = new Date(sunday);
  friday.setDate(sunday.getDate() - 2);
  friday.setHours(20, 0, 0, 0);

  // If Friday 8 PM already passed in local time, push 7 days out so countdown is always positive
  if (friday.getTime() <= now.getTime()) {
    sunday.setDate(sunday.getDate() + 7);
    friday.setDate(friday.getDate() + 7);
  }

  return {
    dropDate: sunday.toISOString().slice(0, 10),
    cutoffIso: friday.toISOString(),
  };
}

